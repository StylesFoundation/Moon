package net.minecraft.util;

public class Vector3d {
   public double x;
   public double y;
   public double z;

   public Vector3d() {
      this.x = this.y = this.z = 0.0;
   }

   public Vector3d(double double1, double double2, double double3) {
      this.x = double1;
      this.y = double2;
      this.z = double3;
   }
}
